import type { Metadata } from "next";
import { isEdition, isLocale, type Edition, type Locale } from "@/i18n/config";
import { getQuoteDict } from "@/i18n/assistant";
import { QuotationView } from "@/components/assistant/QuotationView";

type Params = Promise<{ edition: string; lang: string }>;

export async function generateMetadata({ params }: { params: Params }): Promise<Metadata> {
  const { lang } = await params;
  if (!isLocale(lang)) return {};
  // Quotations are personal documents: keep them out of search engines.
  return { title: getQuoteDict(lang).docTitle, robots: { index: false, follow: false } };
}

/**
 * Indicative quotation generated by the cabin consultant. The quotation data
 * travels in the URL fragment (#q=…), which browsers never send to a server.
 */
export default async function QuotationPage({ params }: { params: Params }) {
  const { edition, lang } = await params;
  if (!isEdition(edition) || !isLocale(lang)) return null;
  return <QuotationView edition={edition as Edition} locale={lang as Locale} />;
}
